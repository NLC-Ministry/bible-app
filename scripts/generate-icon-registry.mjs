import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { icons } from "lucide";

const root = dirname(dirname(fileURLToPath(import.meta.url)));

const DEFAULTS = {
  width: 24,
  height: 24,
  stroke: "currentColor",
  strokeWidth: 2,
  fill: "none",
};

/** Keys ending in Fill render Lucide paths with fill="currentColor" (solid/dense UI). */
function isFilledIconKey(key) {
  return key.endsWith("Fill");
}

function serializeAttrs(attrs) {
  return Object.entries(attrs)
    .map(([key, value]) => `${key}="${String(value).replace(/"/g, "&quot;")}"`)
    .join(" ");
}

function iconNodeToSvg(iconNode, options) {
  const opts = { ...DEFAULTS, ...options };
  const selfClosing = new Set(["path", "line", "polyline", "circle", "rect", "polygon", "ellipse"]);

  const children = iconNode
    .map(([tag, attrs]) => {
      const merged = { ...attrs };
      if (opts.filled) {
        const fillable = new Set(["path", "polygon", "circle", "rect", "ellipse"]);
        if (fillable.has(tag)) {
          merged.fill = "currentColor";
          merged.stroke = "currentColor";
        }
      }
      const attrStr = serializeAttrs(merged);
      if (selfClosing.has(tag)) return `<${tag} ${attrStr}/>`;
      return `<${tag} ${attrStr}></${tag}>`;
    })
    .join("");

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${opts.width}" height="${opts.height}" viewBox="0 0 24 24" fill="${opts.fill}" stroke="${opts.stroke}" stroke-width="${opts.strokeWidth}" stroke-linecap="round" stroke-linejoin="round">${children}</svg>`;
}

/** Pure: the registry file's contents for a manifest. Tests call this instead of writing the tracked file (#328). */
export function buildIconRegistrySource(manifest) {
  const registry = {};
  for (const [key, iconName] of Object.entries(manifest)) {
    const iconNode = icons[iconName];
    if (!iconNode) {
      throw new Error(`generate-icon-registry: missing Lucide icon ${iconName} for key "${key}"`);
    }
    registry[key] = iconNodeToSvg(iconNode, { filled: isFilledIconKey(key) });
  }
  return `/* Auto-generated by scripts/generate-icon-registry.mjs — do not edit */\nwindow.NLC_ICON_SVGS = ${JSON.stringify(registry, null, 2)};\n`;
}

// Only write when run directly (`npm run build`), not when imported.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const manifest = JSON.parse(readFileSync(join(root, "js/design/icon-manifest.json"), "utf8"));
  writeFileSync(join(root, "js/design/icon-registry.js"), buildIconRegistrySource(manifest), "utf8");
  console.log(`generate-icon-registry: wrote ${Object.keys(manifest).length} Lucide icons to js/design/icon-registry.js`);
}
