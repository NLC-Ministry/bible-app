const MS_PER_DAY = 86400000;

// dateStr 為 "YYYY-MM-DD"（台北日期）。以「自 1970-01-01 起的天數」輪流取題庫，
// 跨日必換、題庫全部輪過一輪前不會重複。
export function pickDailyVerse(dateStr, verses = DAILY_VERSES) {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(dateStr || ""));
  if (!m || !verses.length) return verses[0] || null;
  const dayNumber = Math.floor(Date.UTC(Number(m[1]), Number(m[2]) - 1, Number(m[3])) / MS_PER_DAY);
  return verses[((dayNumber % verses.length) + verses.length) % verses.length];
}
